#!/usr/bin/env python3
"""dashboard_assets.py -- single source of truth for dashboard
HTML / CSS / JS, with version interpolation.

Reads the three committed source files and emits
`src/al/web/AutoLinkWebHtml.h` containing the concatenated
form the firmware / host tests consume.

Inputs (committed, edited by hand):

  src/al/web/dashboard.css   raw CSS, no version markers
  src/al/web/dashboard.js    raw JS, with `{{VERSION}}` markers
                             at the three places the firmware
                             version is interpolated into the
                             string at compile time

  src/al/web/dashboard_html_part_a.html
                             markup before the CSS-injection
                             site (DOCTYPE through `<style>`)
  src/al/web/dashboard_html_part_b.html
                             markup between `</style>` and the
                             JS-injection site (header, main,
                             controls, opens `<script>`)
  src/al/web/dashboard_html_part_c.html
                             markup after the JS-injection
                             site (`</script>` through end)

Why three markup files and not one HTML template with
`{{CSS}}` / `{{JS}}` markers: the dashboard tests
(AutoLinkWebTest, HandleRootChunkedTest) grep the header
for specific substrings like `id=\"delayMs\"` or
`<title>AutoLink Monitor</title>`. The simplest way to
preserve those contracts is to leave the markup unmodified
and concatenate the asset strings around it.

The build step is one concern: read three source files,
emit one generated header. No string-merge, no backup,
no verification -- the host test suite (`make test`)
exercises the result end-to-end, so any drift is caught
at the next test run.

Idempotency: re-running with no source changes produces a
byte-identical header.

Usage:
  dashboard_assets.py              # default: repo-root-relative paths
  dashboard_assets.py --check      # exit non-zero if header would change
  dashboard_assets.py --css PATH --js PATH --a PATH --b PATH --c PATH --out PATH
"""
import argparse
import re
import sys
from pathlib import Path


VERSION_MARKER = '{{VERSION}}'


def _read(p: Path) -> str:
    if not p.exists():
        sys.exit(f'dashboard_assets: input not found: {p}')
    return p.read_text(encoding='utf-8')


def _gen_header(css: str, js: str, part_a: str, part_b: str,
                part_c: str) -> str:
    """Build the C++ header. Each `{{VERSION}}` marker in the
    input is split into a string-literal-boundary pair so the
    runtime value of `AUTOLINK_VERSION` is concatenated in
    between the two halves. This keeps `sizeof(DASHBOARD_HTML)`
    a compile-time constant: the linker concatenates adjacent
    string literals and the version macro expands at compile
    time.

    `DASHBOARD_HTML` is built from five adjacent string
    literals (PART_A, CSS, PART_B, JS, PART_C) -- no array
    names in the initializer, so the linker can compute
    `sizeof(DASHBOARD_HTML)` at compile time. The five
    individual `DASHBOARD_*` constants are also exposed for
    the dashboard test (`AutoLinkWebTest`) which greps the
    raw CSS / JS for specific markers.
    """
    def split_version(s: str) -> str:
        if VERSION_MARKER not in s:
            return f'R"DASH({s})DASH"'
        parts = s.split(VERSION_MARKER)
        out_parts = []
        for i, part in enumerate(parts):
            if i > 0:
                out_parts.append('AUTOLINK_VERSION')
            if part:
                out_parts.append(f'R"DASH({part})DASH"')
        return ' '.join(out_parts)

    css_lit = f'R"DASHCSS({css})DASHCSS"' if css else '""'
    js_lit = split_version(js)
    a_lit = split_version(part_a)
    b_lit = split_version(part_b)
    c_lit = split_version(part_c)

    # The single DASHBOARD_HTML initializer concatenates five
    # string literals at compile time. AUTOLINK_VERSION tokens
    # appear inline (they're macro substitutions, not array
    # references). This keeps `sizeof(DASHBOARD_HTML)` a
    # compile-time constant.
    combined = ' '.join(
        part for part in [a_lit, css_lit, b_lit, js_lit, c_lit] if part
    )

    header = (
        "// Auto-generated by build/dashboard_assets.py.\n"
        "// Edit dashboard.css / dashboard.js / dashboard_html_part_*.html,\n"
        "// then re-run dashboard_assets.py. Do not edit by hand.\n"
        "#pragma once\n"
        "#include \"AutoLink.h\"\n"
        "\n"
        "namespace autolink {\n"
        f"static const char DASHBOARD_HTML_PART_A[] = {a_lit};\n"
        f"static const char DASHBOARD_CSS[] = {css_lit};\n"
        f"static const char DASHBOARD_HTML_PART_B[] = {b_lit};\n"
        f"static const char DASHBOARD_JS[] = {js_lit};\n"
        f"static const char DASHBOARD_HTML_PART_C[] = {c_lit};\n"
        "// Adjacent string-literal concatenation is a compile-time\n"
        "// operation: sizeof(DASHBOARD_HTML) is the sum of the five\n"
        "// parts (plus any AUTOLINK_VERSION tokens, expanded by the\n"
        "// preprocessor). httpd's chunked-send loop keeps its length\n"
        "// contract without a runtime strlen().\n"
        f"static const char DASHBOARD_HTML[] = {combined};\n"
        "} // namespace autolink\n"
    )
    return header


def _split_for_parts(html: str) -> tuple[str, str, str]:
    """Split a single HTML template (with {{CSS}} and {{JS}}
    markers) into the three markup files around those
    injection points. Used only by the --from-template
    convenience path, not the default."""
    css_open = html.find('<style>')
    css_close = html.find('</style>')
    js_open = html.find('<script>')
    js_close = html.find('</script>')
    if -1 in (css_open, css_close, js_open, js_close):
        sys.exit('dashboard_assets: --from-template needs <style>...</style>'
                 ' and <script>...</script> in the source.')
    return (
        html[:css_open + len('<style>')],
        html[css_close:js_open + len('<script>')],
        html[js_close:],
    )


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--repo', default='.',
                   help='repo root (default: cwd)')
    p.add_argument('--css',
                   help='path to dashboard.css')
    p.add_argument('--js',
                   help='path to dashboard.js')
    p.add_argument('--a',
                   help='path to dashboard_html_part_a.html')
    p.add_argument('--b',
                   help='path to dashboard_html_part_b.html')
    p.add_argument('--c',
                   help='path to dashboard_html_part_c.html')
    p.add_argument('--out',
                   help='path to AutoLinkWebHtml.h (overwrites)')
    p.add_argument('--check', action='store_true',
                   help='exit non-zero if header would change')
    p.add_argument('--from-template',
                   help='split a single HTML template into the '
                        'three part files, then emit the header. '
                        'The template must contain '
                        '{{CSS}} and {{JS}} markers.')
    args = p.parse_args()

    repo = Path(args.repo).resolve()
    css_p = Path(args.css) if args.css else repo / 'src/al/web/dashboard.css'
    js_p = Path(args.js) if args.js else repo / 'src/al/web/dashboard.js'
    a_p = Path(args.a) if args.a else repo / 'src/al/web/dashboard_html_part_a.html'
    b_p = Path(args.b) if args.b else repo / 'src/al/web/dashboard_html_part_b.html'
    c_p = Path(args.c) if args.c else repo / 'src/al/web/dashboard_html_part_c.html'
    out_p = (Path(args.out) if args.out
             else repo / 'src/al/web/AutoLinkWebHtml.h')

    if args.from_template:
        tpl = _read(Path(args.from_template))
        tpl = tpl.replace('{{CSS}}', '').replace('{{JS}}', '')
        a, b, c = _split_for_parts(tpl)
        a_p.write_text(a, encoding='utf-8')
        b_p.write_text(b, encoding='utf-8')
        c_p.write_text(c, encoding='utf-8')

    css = _read(css_p)
    js = _read(js_p)
    a = _read(a_p)
    b = _read(b_p)
    c = _read(c_p)

    header = _gen_header(css, js, a, b, c)

    if args.check:
        existing = (out_p.read_text(encoding='utf-8')
                    if out_p.exists() else '')
        if existing != header:
            sys.stderr.write(
                f'dashboard_assets: {out_p} is stale '
                f'(regenerate with dashboard_assets.py)\n')
            return 1
        return 0

    out_p.write_text(header, encoding='utf-8')
    print(f'dashboard_assets: wrote {out_p}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
